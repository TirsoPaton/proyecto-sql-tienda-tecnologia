DROP SCHEMA IF EXISTS tienda CASCADE;
CREATE SCHEMA tienda;
SET search_path TO tienda;   -- a partir de aquí, las tablas se crean en 'tienda'

CREATE TABLE categorias (
    id_categoria INT PRIMARY KEY,
    nombre       VARCHAR(50) NOT NULL
);

CREATE TABLE productos (
    id_producto  INT PRIMARY KEY,
    nombre       VARCHAR(60) NOT NULL,
    id_categoria INT REFERENCES categorias(id_categoria),
    precio       NUMERIC(10,2) NOT NULL,
    coste        NUMERIC(10,2) NOT NULL
);

CREATE TABLE clientes (
    id_cliente INT PRIMARY KEY,
    nombre     VARCHAR(80) NOT NULL,
    email      VARCHAR(100),             -- puede ser NULL a propósito
    ciudad     VARCHAR(50),
    fecha_alta DATE,
    segmento   VARCHAR(20)
);

CREATE TABLE tiendas (
    id_tienda INT PRIMARY KEY,
    nombre    VARCHAR(50) NOT NULL,
    ciudad    VARCHAR(50)
);

CREATE TABLE pedidos (
    id_pedido  INT PRIMARY KEY,
    id_cliente INT REFERENCES clientes(id_cliente),
    id_tienda  INT REFERENCES tiendas(id_tienda),
    fecha      DATE NOT NULL,
    canal      VARCHAR(20),
    estado     VARCHAR(20)
);

CREATE TABLE lineas_pedido (
    id_linea    INT PRIMARY KEY,
    id_pedido   INT REFERENCES pedidos(id_pedido),
    id_producto INT REFERENCES productos(id_producto),
    cantidad    INT NOT NULL,
    descuento   NUMERIC(3,2)             -- NULL = sin dato; 0 = sin descuento
);

